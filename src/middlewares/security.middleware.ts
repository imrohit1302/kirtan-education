/**
 * Express 5 compatible recursive NoSQL injection sanitizer.
 * Sanitizes in-place without reassigning read-only query getters.
 */
const sanitizeObject = (target: any): void => {
  if (!target || typeof target !== 'object') return;

  for (const key of Object.keys(target)) {
    if (key.startsWith('$') || key.includes('.')) {
      delete target[key];
    } else if (typeof target[key] === 'object' && target[key] !== null) {
      sanitizeObject(target[key]);
    }
  }
};

export const mongoSanitizer = (req: Request, _res: Response, next: NextFunction): void => {
  if (req.body) sanitizeObject(req.body);
  if (req.params) sanitizeObject(req.params);
  if (req.query) sanitizeObject(req.query);
  next();
};

export const hppMiddleware = hpp({
  whitelist: ['sort', 'page', 'limit', 'fields', 'role', 'status'],
});
